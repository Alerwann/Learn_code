from typing import Protocol

from app.schemas.definition_shema import DefinititionIn, DefinititionOut


class DefRepository(Protocol):
    """Définition du protocol"""

    def createDef(self, data: DefinititionIn) -> DefinititionOut: ...
    def getAllDef(self) -> list[DefinititionOut] | None: ...
    def getDefById(self, def_id: int) -> DefinititionOut | None: ...
    def getDefByCategory(self, def_category) -> list[DefinititionOut] | None: ...
    def updateCategory(self, data: DefinititionOut) -> DefinititionOut | None: ...
    def deleteCategory(self, def_id: int) -> bool: ...

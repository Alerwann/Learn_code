from typing import Protocol

from app.schemas.definition_shema import definitionIn, definitionOut


class DefRepository(Protocol):
    """Définition du protocol"""

    def createDef(self, data: definitionIn) -> definitionOut: ...
    def getAllDef(self) -> list[definitionOut] | None: ...
    def getDefById(self, def_id: int) -> definitionOut | None: ...
    def getDefByCategory(self, def_category) -> list[definitionOut] | None: ...
    def updateCategory(self, data: definitionOut) -> definitionOut | None: ...
    def deleteCategory(self, def_id: int) -> bool: ...
